Object.entries(supplementalNamespaces).forEach(([language, namespaces]) => {
  Object.entries(namespaces).forEach(([namespace, translation]) => {
    resources[language].translation[namespace] = {
      ...resources[language].translation[namespace],
      ...translation,
    };
  });
});

// A few legacy resource additions were authored alongside the locale object.
// Normalize them into the translation namespace so every locale has the same
// shape and react-i18next can resolve the keys.
['en', 'hi', 'gu'].forEach((language) => {
  ['faq', 'auth', 'common', 'footer', 'tripPlanner'].forEach((namespace) => {
    if (resources[language][namespace]) {
      resources[language].translation[namespace] = {
        ...resources[language].translation[namespace],
        ...resources[language][namespace],
      };
      delete resources[language][namespace];
    }
  });
});

const initialLanguage =
  typeof window !== 'undefined' ? localStorage.getItem('tripnest_language') || 'en' : 'en';

